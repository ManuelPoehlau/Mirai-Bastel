"""Turn `results/*.json` into `results/SUMMARY.md`: the tables the report quotes, regenerated from the raw numbers.

    python experiments/surface_slide/summarize.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"

GROUPS = [
    ("A. Sphere", ("A1", "A2", "A3", "A4", "A5")),
    ("B. Cylinder and capsule", ("B",)),
    ("C. Concave U", ("C",)),
    ("D. Gollum cage (1 670 vertices)", ("D_cage",)),
    ("D. Gollum high resolution (21 875 vertices)", ("D_hires",)),
]


def fmt(x, digits: int = 3) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "-"
    if isinstance(x, int):
        return str(x)
    if x == 0:
        return "0"
    if abs(x) < 1e-3 or abs(x) >= 1e4:
        return f"{x:.1e}"
    return f"{x:.{digits}f}".rstrip("0").rstrip(".") if abs(x) < 10 else f"{x:.1f}"


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def scenario_group(data: dict, prefixes) -> tuple[str, list[str]]:
    names = [n for n in data if n.startswith(prefixes)]
    cands: list[str] = []
    for n in names:
        for c in data[n]["candidates"]:
            if c not in cands:
                cands.append(c)
    rows = []
    for c in cands:
        present = [n for n in names if c in data[n]["candidates"]]
        ms = [data[n]["candidates"][c] for n in present]
        e = [data[n] for n in present]
        trk = max(m["dev_tracked_max_over_frames_rel_edge"] for m in ms)
        ana = [m["dev_analytic"]["max"] / s["mean_edge"] for m, s in zip(ms, e) if "dev_analytic" in m]
        intended = [m["err_intended"]["max"] / s["mean_edge"] for m, s in zip(ms, e) if "err_intended" in m]
        wrong = [m["wrong_region_any_frame"] for m in ms if "wrong_region_any_frame" in m]
        wrong_of = [m["n_points"] for m in ms if "wrong_region_any_frame" in m]
        jumps = sum(m["continuity"]["region_jumps"] for m in ms)
        ratio = max(m["continuity"]["max_step_ratio"] for m in ms)
        p99 = max(m["continuity"]["p99_step_ratio"] for m in ms)
        rigid = [m["edges_rigid"] for n, m in zip(present, ms) if "rigid" in n and "edges_rigid" in m]
        soft = [(m["edges"]["mean_abs_rel"], m["edges_free_move"]["mean_abs_rel"]) for n, m in zip(present, ms)
                if "patch" in n or n.startswith("D_")]
        soft = [(a, b) for a, b in soft if b > 0]
        folds = sum(m.get("folded_tris", 0) for n, m in zip(present, ms) if "probes" not in n)
        folds_free = sum(m.get("folded_tris_free_move", 0) for n, m in zip(present, ms) if "probes" not in n)
        closure = [m["closure"]["max"] / s["mean_edge"] for m, s in zip(ms, e) if "closure" in m]
        flags = {k: sum(m["flags"][k] for m in ms) for k in ("fallback", "boundary", "stuck", "blocked", "maxiter")}
        flag_text = ", ".join(f"{k} {v}" for k, v in flags.items() if v) or "-"
        rows.append([
            f"`{c}`", len(ms), fmt(trk), fmt(max(ana)) if ana else "-", fmt(max(intended)) if intended else "-",
            f"{sum(wrong)} / {sum(wrong_of)}" if wrong else "-", jumps, fmt(ratio, 2), fmt(p99, 2),
            f"{fmt(sum(r['mean_abs_rel'] for r in rigid) / len(rigid))} / {fmt(max(r['max_abs_rel'] for r in rigid))}"
            if rigid else "-",
            f"{fmt(sum(a for a, _ in soft) / len(soft))} ({fmt(sum(b for _, b in soft) / len(soft))})" if soft else "-",
            f"{folds} ({folds_free})", fmt(max(closure)) if closure else "-", flag_text,
            fmt(sum(m["update_ms_mean"] for m in ms) / len(ms), 2)])
    header = ["candidate", "runs", "tracked dev max [h]", "analytic dev max [h]", "to exact geodesic end [h]",
              "wrong region", "region jumps", "step ratio max", "step ratio p99 (worst run)",
              "rigid edges mean / max", "soft edges mean (free move)", "folded tris (free move)",
              "loop closure max [h]", "flags", "update ms"]
    return table(header, rows), names


def main() -> int:
    out = ["# Surface Slide prototype - result tables", "",
           "Generated by `summarize.py` from `scenarios.json`, `studies.json` and `bench.json` in this folder. "
           "`[h]` = in mean edge lengths of the reference mesh. Every number is a measurement of the prototype; "
           "see the report for what each column means and for the interpretation.", ""]
    sc_path = RESULTS / "scenarios.json"
    if sc_path.exists():
        data = json.loads(sc_path.read_text(encoding="utf-8"))
        out += ["## 1. Scenarios, aggregated per geometry", "",
                "Aggregation over the runs of a group: maxima for deviations, ratios and closure; sums for wrong-region "
                "vertices, region jumps, folded triangles and flags; means for edge-length changes and time.", ""]
        for title, prefixes in GROUPS:
            text, names = scenario_group(data, prefixes)
            if not names:
                continue
            out += [f"### {title}", "", f"{len(names)} scenarios: " + ", ".join(f"`{n}`" for n in names) + ".", "", text]
        out += ["## 2. Scenario list", "",
                table(["scenario", "vertices", "frames", "drag [h]", "what"],
                      [[f"`{n}`", e["n_points"], e["frames"], fmt(e["drag_max_rel_edge"], 1), e["notes"]]
                       for n, e in data.items()])]
        # edge-length histograms of the recommended candidate
        out += ["## 3. Distribution of edge-length changes (`geodesic_pursuit[transport]`, soft patches)", "",
                "Share of the edges with a moved end, by relative length change |dl| / l; `free` = the same weights "
                "moved freely in space.", ""]
        rows = []
        for n, e in data.items():
            m = e["candidates"].get("geodesic_pursuit[transport]")
            if m is None or "edges" not in m or "loop" in n:
                continue
            ed, fr = m["edges"], m["edges_free_move"]
            tot = max(sum(ed["hist"]), 1)
            tot_f = max(sum(fr["hist"]), 1)
            rows.append([f"`{n}`", ed["n_edges"]] + [f"{100 * a / tot:.0f} ({100 * b / tot_f:.0f})"
                                                     for a, b in zip(ed["hist"], fr["hist"])])
        out.append(table(["scenario", "edges", "<1 %", "1-2 %", "2-5 %", "5-10 %", "10-20 %", "20-50 %", ">50 %"], rows))

    st_path = RESULTS / "studies.json"
    if st_path.exists():
        st = json.loads(st_path.read_text(encoding="utf-8"))
        if "density" in st:
            out += ["## 4. Mesh density on the sphere (R = 1)", "", st["density"]["note"] + ".", ""]
            rows = []
            for r in st["density"]["rows"]:
                rows.append([r["n"], r["nv"], fmt(r["mean_edge"]), fmt(r["sag_h2_over_8R"]),
                             f"{fmt(r['flat']['radial_dev_max'])} ({fmt(r['flat']['radial_dev_max_rel_edge'])} h)",
                             f"{fmt(r['phong_0.5']['radial_dev_max'])}", f"{fmt(r['phong_0.75']['radial_dev_max'])}",
                             f"{fmt(r['closest_global']['radial_dev_max'])}",
                             f"{fmt(r['flat']['rigid_edge_mean'])} / {fmt(r['flat']['rigid_edge_max'])}",
                             f"{fmt(r['closest_global']['rigid_edge_mean'])} / {fmt(r['closest_global']['rigid_edge_max'])}"])
            out.append(table(["n", "vertices", "mean edge h", "h^2 / 8R", "radial dev max, flat", "Phong 0.5",
                              "Phong 0.75", "closest_global (flat)", "rigid edges mean / max, pursuit",
                              "rigid edges, closest_global"], rows))
            if "creases" in st["density"]:
                out += ["Phong evaluation across creases (U shape; distance of the evaluated point to the flat "
                        "reference, largest over the drag):", "",
                        table(["scenario", "Phong 0.5 off the flat reference max [h]"],
                              [[f"`{c['scenario']}`", fmt(c["phong_off_the_flat_reference_max_rel_edge"])]
                               for c in st["density"]["creases"]])]
        if "erosion" in st:
            out += ["## 5. Repeated gestures", "", st["erosion"]["note"] + ".", ""]
            for name in ("sphere_n8", "sphere_n16"):
                e = st["erosion"][name]
                rows = []
                for mode, series in e["rows"].items():
                    for r in series[1::2]:
                        rows.append([mode, r["gestures"], f"{r['mean_radius']:.5f}", f"{r['min_radius']:.5f}",
                                     f"{r['max_radius']:.5f}"])
                out += [f"### {name} (mean edge {fmt(e['mean_edge'])}, R = 1)", "",
                        table(["reference / evaluation", "gestures", "mean radius", "min radius", "max radius"], rows)]
            e = st["erosion"]["gollum_cage"]
            rows = []
            for mode, series in e["rows"].items():
                for r in series[1::2]:
                    rows.append([mode, r["gestures"], r["moved_vertices"], fmt(r["dist_to_original_mean_rel_edge"]),
                                 fmt(r["dist_to_original_max_rel_edge"])])
            out += ["### Gollum cage: distance of the moved vertices to the *original flat* cage surface", "",
                    table(["reference / evaluation", "gestures", "moved vertices", "mean [h]", "max [h]"], rows)]
            if "gollum_cage_triangulation_difference" in st["erosion"]:
                d = st["erosion"]["gollum_cage_triangulation_difference"]
                out += ["### Gollum cage: how far two triangulations of the same polygons are apart", "",
                        "Centroids of the triangles of one triangulation against the surface of the other.", "",
                        table(["pair", "triangles differing", "mean [h]", "p95 [h]", "max [h]"],
                              [[k, v["triangles_differing"], fmt(v["mean_rel_edge"]), fmt(v["p95_rel_edge"]),
                                fmt(v["max_rel_edge"])] for k, v in d.items()])]
        if "drift" in st:
            out += ["## 6. Path dependence and drift", "", st["drift"]["note"] + ".", ""]
            for name, e in st["drift"].items():
                if name == "note":
                    continue
                rows = []
                for c, r in e["rows"].items():
                    settle = (f"{r['lagging_when_drag_stops']} lagging, {r['settle_steps_quarter_edge']} steps, then gap "
                              f"{fmt(r['gap_to_absolute_after_settle_rel_edge'])} h"
                              if "lagging_when_drag_stops" in r else "-")
                    rows.append([f"`{c}`", fmt(r["path_spread_max_rel_edge"]), fmt(r["jitter_closure_max_rel_edge"]),
                                 fmt(r["jitter_closure_mean_rel_edge"]), fmt(r["jitter_max_step_ratio"], 2),
                                 fmt(r["jitter_p99_step_ratio"], 2), fmt(r["paths_max_step_ratio"], 2),
                                 r["jitter_region_jumps"], "yes" if r["deterministic"] else "NO", settle])
                out += [f"### {name} ({e['n_points']} vertices)", "",
                        table(["candidate", "path spread max [h]", "jitter closure max [h]", "mean [h]",
                               "jitter step ratio max", "p99", "paths step ratio max", "region jumps", "same bits twice",
                               "after the drag stops (pursuit)"], rows)]
        if "symmetry" in st:
            out += ["## 7. Symmetry", "", st["symmetry"]["note"] + ".", ""]
            for name, e in st["symmetry"].items():
                if not isinstance(e, dict) or "candidates" not in e:
                    continue
                rows = [[f"`{c}`", fmt(r["independent_vs_mirror_line_rel_edge"]),
                         fmt(r["independent_vs_mirror_wiggle_rel_edge"]),
                         fmt(r["seam_off_plane_unconstrained_rel_edge"]), fmt(r["seam_dev_after_plane_snap_rel_edge"])]
                        for c, r in e["candidates"].items()]
                out += [f"### {name}", "",
                        f"driven {e['n_driven']} (seam {e['n_seam']}), mirrored {e['n_mirrored']}, unpaired "
                        f"{e['unpaired_in_falloff']}; triangles without a mirror image: "
                        f"{e['triangles_without_mirror_image']}; seam vertices with an in-plane drag: off the plane "
                        f"before the snap {fmt(e['seam_in_plane_drag']['off_plane_before_snap_rel_edge'])} h, off the "
                        f"surface after it {fmt(e['seam_in_plane_drag']['dev_after_snap_rel_edge'])} h.", "",
                        table(["candidate", "I vs M, straight drag [h]", "I vs M, wiggly drag [h]",
                               "seam vertex off the plane, free drag [h]", "off the surface after a plane snap [h]"],
                              rows)]
                if "crossing_the_plane" in e:
                    cr = e["crossing_the_plane"]
                    out += [table(["crossing the plane (drag 6 h towards -x)", "driven vertices on the far side",
                                   "exactly on the plane", "stopped at the barrier"],
                                  [[k, v["driven_now_on_minus_side"], v["driven_exactly_on_plane"],
                                    v["stopped_at_barrier"]] for k, v in cr.items()])]
            if "gollum_cage_triangulation" in st["symmetry"]:
                t = st["symmetry"]["gollum_cage_triangulation"]
                out += ["### Gollum cage: the mirror image of a driven result against the reference", "",
                        table(["triangulation", "triangles without a mirror image", "mirrored result off the reference max [h]"],
                              [[k, f"{v['triangles_without_mirror_image']} / {v['triangles']}",
                                fmt(v["mirrored_result_off_reference_max_rel_edge"])] for k, v in t.items()])]
            if "gollum_cage_seam_curve_slide" in st["symmetry"]:
                s = st["symmetry"]["gollum_cage_seam_curve_slide"]
                out += [f"Seam curve slide on the cage: {s['walks']} walks, largest |plane coordinate| "
                        f"{fmt(s['max_abs_plane_coordinate'])}, largest distance to the reference "
                        f"{fmt(s['max_distance_to_reference'])}, {s['stopped_at_seam_end']} stopped at a seam end.", ""]
        if "weights" in st:
            out += ["## 8. Soft-selection weights", "", st["weights"]["note"] + ".",
                    "Per weight: the largest distance to the tracked reference surface [h] and the mean straight-line "
                    "travel relative to the weight-1 vertices (min .. max).", ""]
            for name, e in st["weights"].items():
                if name == "note":
                    continue
                rows = []
                for c, r in e["rows"].items():
                    pw = r["per_weight"]
                    cells = []
                    for k in ("0.25", "0.5", "1"):
                        v = pw[k]
                        cells.append(f"{fmt(v['dev_max_rel_edge'])}; {v['travel_mean_over_full']:.2f} "
                                     f"({v['travel_min_over_full']:.2f} .. {v['travel_max_over_full']:.2f})")
                    rows.append([f"`{c}`", "yes" if pw["0"]["moved_bit_exact_none"] else "NO"] + cells +
                                [f"{fmt(r['edges_mean'])} / {fmt(r['edges_max'])}",
                                 f"{fmt(r['edges_free_mean'])} / {fmt(r['edges_free_max'])}",
                                 f"{r['folded']} ({r['folded_free']})", fmt(r["max_step_ratio"], 2)])
                out += [f"### {name} ({e['n_points']} vertices)", "",
                        table(["candidate", "w = 0 unmoved (bits)", "w = 0.25: dev; travel", "w = 0.5: dev; travel",
                               "w = 1: dev; travel", "edges mean / max", "free move mean / max", "folded tris (free)",
                               "step ratio max"], rows)]
        if "cursor" in st:
            out += ["## 9. Pivot against the cursor (front view)", "", st["cursor"]["note"] + ".", ""]
            rows = []
            for name, e in st["cursor"].items():
                if name == "note":
                    continue
                r = e["rows"]
                s = e["pivot_under_cursor_solve"]
                rows.append([f"`{name}`", f"{e['pivot_normal_towards_viewer']:.2f}",
                             f"{r['geodesic_pursuit[transport]']['screen_follow']:.2f}",
                             f"{r['geodesic_abs[transport][full]']['screen_follow']:.2f}",
                             f"{r['closest_global']['screen_follow']:.2f}",
                             f"{r['ray_view']['screen_follow']:.2f}" if "ray_view" in r else "-",
                             f"{s['screen_follow']:.2f}", fmt(s["residual_max_rel_edge"], 2),
                             fmt(s["surface_speed_over_cursor_speed_max"], 1), fmt(s["traces_per_frame"], 1)])
            out.append(table(["scenario", "pivot normal . view", "pursuit (tangent length)", "abs (full length)",
                              "closest_global", "ray_view", "cursor solve: follow", "residual max [h]",
                              "surface speed / cursor speed max", "traces per frame"], rows))

    b_path = RESULTS / "bench.json"
    if b_path.exists():
        b = json.loads(b_path.read_text(encoding="utf-8"))
        out += ["## 10. Performance", "", f"Python {b['python']}, NumPy {b['numpy']}, container (4 x Xeon 2.3 GHz).", ""]
        rows = [[m["name"], m["nv"], m["nt"], fmt(m["triangulate_ms"], 1), fmt(m["refsurface_build_ms_best"], 1),
                 fmt(m["refsurface_build_peak_mb"], 1), fmt(m["bytes_tracer_arrays"] / 1e6, 1),
                 fmt(m["bytes_per_vertex_tracer"], 0), fmt(m["closest_grid_build_ms"], 1),
                 fmt(m["bytes_closest_grid"] / 1e6, 1), fmt(m["edge_graph_ms"], 1)] for m in b["meshes"]]
        out += ["### Setup and memory", "",
                table(["mesh", "vertices", "triangles", "triangulate ms", "reference arrays ms", "build peak MB",
                       "tracer arrays MB", "bytes / vertex", "closest-point grid ms", "grid MB", "edge graph ms"], rows)]
        for m in b["meshes"]:
            for case in m["cases"]:
                cands = list(case["updates"])
                dists = list(case["updates"]["geodesic_pursuit[transport]"])
                rows = []
                for c in cands:
                    row = [f"`{c}`"]
                    for d in dists:
                        u = case["updates"][c].get(d)
                        row.append("not timed" if u is None else
                                   f"{fmt(u['update_ms_mean'], 2)} / {fmt(u['update_ms_max'], 2)} ({u['max_passes']})")
                    rows.append(row)
                out += [f"### {m['name']}: {case['affected']} affected vertices (radius {fmt(case['radius_rel_edge'], 1)} h)",
                        "", f"begin: weights (Dijkstra) {fmt(case['weights_dijkstra_ms'], 1)} ms, transport frames "
                            f"{fmt(case['transport_frames_ms'], 1)} ms. Per update: mean / worst frame in ms (passes "
                            "= edge crossings of the longest path).", "",
                        table(["candidate"] + [f"drag to {d} h" for d in dists], rows)]
    (RESULTS / "SUMMARY.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("->", RESULTS / "SUMMARY.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
